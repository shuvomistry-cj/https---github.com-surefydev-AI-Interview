            cursor.execute(
                """
                INSERT INTO sessions
                    (session_code, session_link, language, status, created_at, founder_name, startup_name,
                    profile_id, job_id, applicant_user_id, employer_id, interview_token, interview_id, duration_seconds, onboarding_completed)
                VALUES (%s, %s, %s, 'created', %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, TRUE)
                """,
                (session_code, f"{base_url}/session/{session_code}", language, now, full_name or "Candidate",
                 job["job_name"], profile_id, job_id, applicant_user_id, employer_id, token, interview_id, job["duration_seconds"]),
            )
