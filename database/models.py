def get_job_interview_stats(job_id):
    with _connect() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                """
                SELECT
                    COUNT(*) AS total_candidates,
                    COUNT(*) FILTER (WHERE sessions.status IN ('saved', 'evaluated')) AS completed_candidates,
                    COUNT(*) FILTER (WHERE sessions.result_score IS NOT NULL) AS evaluated_candidates,
                    COALESCE(ROUND(AVG(sessions.result_score)::numeric, 1), 0) AS average_score,
                    COUNT(*) FILTER (WHERE sessions.result_tag = 'Poor') AS poor_count,
                    COUNT(*) FILTER (WHERE sessions.result_tag = 'Satisfactory') AS satisfactory_count,
                    COUNT(*) FILTER (WHERE sessions.result_tag = 'Good') AS good_count,
                    COUNT(*) FILTER (WHERE sessions.result_tag = 'Well Done') AS well_done_count
                FROM sessions
                WHERE sessions.job_id = %s
                """,
                (job_id,),
            )
            summary = cursor.fetchone()
            cursor.execute(
                """
                SELECT sessions.id, sessions.session_code, sessions.interview_id,
                       sessions.applicant_user_id, sessions.employer_id, sessions.founder_name,
                       user_profiles.email_address, sessions.language, sessions.status,
                       sessions.created_at, sessions.started_at, sessions.ended_at,
                       sessions.result_score, sessions.result_tag, sessions.evaluation_json,
                       sessions.evaluation_error,
                       sessions.webhook_status, recordings.id AS recording_id,
                       recordings.duration AS recording_duration,
                       recordings.file_path AS recording_path,
                       latest_job.edited_video_url
                FROM sessions
                LEFT JOIN user_profiles ON user_profiles.id = sessions.profile_id
                LEFT JOIN LATERAL (
                    SELECT recordings.* FROM recordings
                    WHERE recordings.session_id = sessions.id
                    ORDER BY recordings.id DESC LIMIT 1
                ) AS recordings ON TRUE
                LEFT JOIN LATERAL (
                    SELECT video_edit_jobs.edited_video_url FROM video_edit_jobs
                    WHERE video_edit_jobs.session_id = sessions.id
                    ORDER BY video_edit_jobs.id DESC LIMIT 1
                ) AS latest_job ON TRUE
                WHERE sessions.job_id = %s
                ORDER BY sessions.created_at DESC
                """,
                (job_id,),
            )
            return {"summary": summary, "candidates": cursor.fetchall()}


@contextmanager
def _connect():
    conn = psycopg.connect(_database_url(), row_factory=dict_row)
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _database_url():
    url = os.getenv("DATABASE_URL", "").strip()
    if url:
        return url

    host = os.getenv("POSTGRES_HOST", "localhost")
    port = os.getenv("POSTGRES_PORT", "5432")
    database = os.getenv("POSTGRES_DB", "surefy_interviews")
    user = os.getenv("POSTGRES_USER", "postgres")
    password = os.getenv("POSTGRES_PASSWORD", "")

    return (
        f"host={host} port={port} dbname={database} "
        f"user={user} password={password}"
    )


def _new_session_code():
    alphabet = string.ascii_uppercase + string.digits
    while True:
        code = "".join(secrets.choice(alphabet) for _ in range(8))
        if not get_session_by_code(code):
            return code


def _now():
    return datetime.utcnow().isoformat(timespec="seconds") + "Z"


def _normalise_language(language):
    value = str(language or "en").strip().lower()
    return value if value.isalpha() and 2 <= len(value) <= 8 else "en"
