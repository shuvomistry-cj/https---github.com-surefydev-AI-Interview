def update_video_edit_job(event_id, **changes):
    allowed_fields = {
        "external_job_id",
        "status",
        "submitted_at",
        "completed_at",
        "edited_file_path",
        "edited_video_url",
        "edited_duration",
        "thumbnail_url",
        "error_message",
    }
    updates = {key: value for key, value in changes.items() if key in allowed_fields}
    if not updates:
        return get_video_edit_job_by_event_id(event_id)

    updates["updated_at"] = _now()
    assignments = ", ".join(f"{field} = %s" for field in updates)
    values = list(updates.values()) + [event_id]
    with _connect() as conn:
        with conn.cursor() as cursor:
            cursor.execute(
                f"UPDATE video_edit_jobs SET {assignments} WHERE event_id = %s RETURNING *",
                values,
            )
            return cursor.fetchone()


