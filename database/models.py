def replace_interview_questions(job_id, questions, language=None):
    now = _now()
    with _connect() as conn:
        with conn.cursor() as cursor:
            if language:
                cursor.execute("DELETE FROM interview_questions WHERE job_id = %s AND language = %s", (job_id, language))
            else:
                cursor.execute("DELETE FROM interview_questions WHERE job_id = %s", (job_id,))
            for index, question in enumerate(questions, 1):
                cursor.execute(
                    """
                    INSERT INTO interview_questions
                        (job_id, question_order, language, question_type, question_text, expected_answer, options_json, created_at)
                    VALUES (%s, %s, %s, %s, %s, %s, %s, %s)
                    """,
                    (
                        job_id,
                        index,
                        question.get("language", "en"),
                        question.get("question_type", "description"),
                        question.get("question_text", "").strip(),
                        question.get("expected_answer", "").strip(),
                        json.dumps(question.get("options", [])),
                        now,
                    ),
                )
    return get_interview_questions(job_id)


